interface SDKConfig {
  accessToken: string;        // 🔒 Sensitive
  phoneNumberId: string;
  apiVersion: string;
  timeout: number;
  retryAttempts: number;
  baseURL: string;
  webhookSecret?: string;     // 🔒 Sensitive
  debug: boolean;
}

// Safe config excludes all secrets
type SafeConfig = Omit<SDKConfig, 'accessToken' | 'webhookSecret'>;

class WhatsAppClient {
  private config: SDKConfig;

  constructor(config: SDKConfig) {
    this.config = config;
    this.logInitialization();
  }

  // Log initialization without exposing secrets
  private logInitialization(): void {
    const safeConfig: SafeConfig = {
      phoneNumberId: this.config.phoneNumberId,
      apiVersion: this.config.apiVersion,
      timeout: this.config.timeout,
      retryAttempts: this.config.retryAttempts,
      baseURL: this.config.baseURL,
      debug: this.config.debug
    };

    console.log('✅ WhatsApp SDK initialized with config:', safeConfig);
    // No secrets in logs!
  }

  // Public method to get safe config
  getConfig(): SafeConfig {
    const { accessToken, webhookSecret, ...safeConfig } = this.config;
    return safeConfig;
  }
}

const client = new WhatsAppClient({
  accessToken: 'EAAxxxxxxxxxxxxxxx',  // Secret
  phoneNumberId: '123456789',
  apiVersion: 'v17.0',
  timeout: 5000,
  retryAttempts: 3,
  baseURL: 'https://graph.facebook.com',
  webhookSecret: 'webhook_secret_xxx',  // Secret
  debug: true
});

console.log('Public config:', client.getConfig());

console.log('✅ Example 2: Safe Configuration Logging completed\n');


