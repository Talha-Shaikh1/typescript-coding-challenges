// Example 6: Combining Omit with Other Utilities
// ============================================

interface Employee {
  id: string;
  firstName: string;
  lastName: string;
  email: string;
  password: string;
  department: string;
  role: string;
  salary: number;
  ssn: string;
  startDate: Date;
  endDate?: Date;
  isActive: boolean;
}

// Omit sensitive, then make optional for updates
type UpdateEmployeeInput = Partial<Omit<Employee, 'id' | 'password' | 'salary' | 'ssn'>>;

// Omit sensitive, then pick only specific fields
type EmployeeCard = Pick<Omit<Employee, 'password' | 'salary' | 'ssn'>, 'id' | 'firstName' | 'lastName' | 'role'>;

// Omit internal fields for public API
type PublicEmployee = Omit<Employee, 'password' | 'salary' | 'ssn' | 'endDate'>;

function updateEmployee(id: string, updates: UpdateEmployeeInput): void {
  console.log(`Updating employee ${id}:`, updates);
  // Can update some fields, but not id, password, salary, ssn
}

function displayEmployeeCard(employee: EmployeeCard): void {
  console.log(`${employee.firstName} ${employee.lastName} - ${employee.role}`);
}

// Demonstrate usage
updateEmployee('emp-1', {
  department: 'Engineering',
  role: 'Senior Developer'
});

const employeeCard: EmployeeCard = {
  id: 'emp-1',
  firstName: 'John',
  lastName: 'Doe',
  role: 'Senior Developer'
};

displayEmployeeCard(employeeCard);

console.log('✅ Example 6: Combining Omit with Other Utilities completed\n');


