// Example 5: Database Models vs DTOs
// ============================================

interface UserEntity {
  // Database fields
  id: string;
  email: string;
  passwordHash: string;
  salt: string;
  emailVerified: boolean;
  verificationToken?: string;

  // User data
  firstName: string;
  lastName: string;
  phoneNumber?: string;

  // Metadata
  createdAt: Date;
  updatedAt: Date;
  lastLoginAt?: Date;
  loginCount: number;

  // Internal
  deletedAt?: Date;
  deletedBy?: string;
}

// DTO for registration - exclude internal fields
type RegisterUserDTO = Omit<
  UserEntity,
  'id' | 'passwordHash' | 'salt' | 'emailVerified' | 'verificationToken' |
  'createdAt' | 'updatedAt' | 'lastLoginAt' | 'loginCount' | 'deletedAt' | 'deletedBy'
> & {
  password: string;  // Plain password in DTO, hashed in entity
};

// DTO for user profile - exclude sensitive and internal fields
type UserProfileDTO = Omit<
  UserEntity,
  'passwordHash' | 'salt' | 'verificationToken' | 'deletedAt' | 'deletedBy'
>;

// DTO for public display
type PublicUserDTO = Omit<
  UserEntity,
  'email' | 'passwordHash' | 'salt' | 'emailVerified' | 'verificationToken' |
  'phoneNumber' | 'lastLoginAt' | 'loginCount' | 'deletedAt' | 'deletedBy'
>;

class UserRepository {
  private users: Map<string, UserEntity> = new Map();

  register(dto: RegisterUserDTO): PublicUserDTO {
    const { password, ...userData } = dto;

    const entity: UserEntity = {
      ...userData,
      id: `user-${Date.now()}`,
      passwordHash: this.hashPassword(password),
      salt: this.generateSalt(),
      emailVerified: false,
      verificationToken: this.generateToken(),
      createdAt: new Date(),
      updatedAt: new Date(),
      loginCount: 0
    };

    this.users.set(entity.id, entity);
    console.log(`User registered: ${entity.email}`);

    // Return public DTO
    return {
      id: entity.id,
      firstName: entity.firstName,
      lastName: entity.lastName,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt
    };
  }

  getProfile(id: string): UserProfileDTO | undefined {
    const entity = this.users.get(id);
    if (!entity) return undefined;

    // Exclude sensitive fields
    const { passwordHash, salt, verificationToken, deletedAt, deletedBy, ...profile } = entity;
    return profile;
  }

  getPublicProfile(id: string): PublicUserDTO | undefined {
    const entity = this.users.get(id);
    if (!entity) return undefined;

    // Only public fields
    return {
      id: entity.id,
      firstName: entity.firstName,
      lastName: entity.lastName,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt
    };
  }

  private hashPassword(password: string): string {
    return `hashed_${password}`;
  }

  private generateSalt(): string {
    return 'salt_' + Math.random();
  }

  private generateToken(): string {
    return 'token_' + Math.random();
  }
}

const userRepo = new UserRepository();

// Register new user
const registeredUser = userRepo.register({
  email: 'john@example.com',
  firstName: 'John',
  lastName: 'Doe',
  phoneNumber: '+1234567890',
  password: 'secure_password'
});

console.log('Registered user (public):', registeredUser);

// Get user profile (includes email, but not password)
const profile = userRepo.getProfile(registeredUser.id);
console.log('User profile:', profile);

// Get public profile (minimal data)
const publicProfile = userRepo.getPublicProfile(registeredUser.id);
console.log('Public profile:', publicProfile);

console.log('✅ Example 5: Database Models vs DTOs completed\n');


