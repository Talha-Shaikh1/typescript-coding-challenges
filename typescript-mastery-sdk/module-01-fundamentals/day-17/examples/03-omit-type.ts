// Example 4: API Request vs Response Types
// ============================================

interface Product {
  id: string;
  name: string;
  description: string;
  price: number;
  stock: number;
  categoryId: string;
  vendorId: string;
  sku: string;
  weight: number;
  images: string[];
  createdAt: Date;
  updatedAt: Date;
  createdBy: string;
  updatedBy: string;
}

// POST /products - User doesn't send system-generated fields
type CreateProductRequest = Omit<
  Product,
  'id' | 'createdAt' | 'updatedAt' | 'createdBy' | 'updatedBy'
>;

// PATCH /products/:id - User can update some fields
type UpdateProductRequest = Partial<
  Omit<Product, 'id' | 'createdAt' | 'updatedAt' | 'createdBy' | 'updatedBy' | 'vendorId'>
>;

// GET /products - Response includes everything
type ProductResponse = Product;

// GET /products (list) - Response excludes some heavy fields
type ProductListResponse = Omit<Product, 'description' | 'createdBy' | 'updatedBy'>;

class ProductAPI {
  private products: Map<string, Product> = new Map();

  // POST /products
  createProduct(userId: string, request: CreateProductRequest): ProductResponse {
    const product: Product = {
      ...request,
      id: `prod-${Date.now()}`,
      createdAt: new Date(),
      updatedAt: new Date(),
      createdBy: userId,
      updatedBy: userId
    };

    this.products.set(product.id, product);
    console.log(`Product created: ${product.name}`);
    return product;
  }

  // PATCH /products/:id
  updateProduct(
    id: string,
    userId: string,
    request: UpdateProductRequest
  ): ProductResponse | undefined {
    const existing = this.products.get(id);

    if (!existing) {
      return undefined;
    }

    const updated: Product = {
      ...existing,
      ...request,
      updatedAt: new Date(),
      updatedBy: userId
    };

    this.products.set(id, updated);
    console.log(`Product updated: ${id}`);
    return updated;
  }

  // GET /products/:id
  getProduct(id: string): ProductResponse | undefined {
    return this.products.get(id);
  }

  // GET /products (list)
  listProducts(): ProductListResponse[] {
    return Array.from(this.products.values()).map(product => {
      const { description, createdBy, updatedBy, ...listItem } = product;
      return listItem;
    });
  }
}

const productAPI = new ProductAPI();

// Create product
const product = productAPI.createProduct('admin-1', {
  name: 'Wireless Keyboard',
  description: 'Mechanical wireless keyboard with RGB',
  price: 89.99,
  stock: 50,
  categoryId: 'cat-1',
  vendorId: 'vendor-1',
  sku: 'WK-001',
  weight: 1.2,
  images: ['image1.jpg', 'image2.jpg']
});

// Update product
productAPI.updateProduct(product.id, 'admin-1', {
  price: 79.99,
  stock: 45
});

// List products (lightweight)
const productList = productAPI.listProducts();
console.log('Product list:', productList);

console.log('✅ Example 4: API Request/Response Types completed\n');


