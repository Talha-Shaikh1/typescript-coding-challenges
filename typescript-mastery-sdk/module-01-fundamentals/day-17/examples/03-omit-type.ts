// ============================================
// Example 1: Basic Omit Usage
// ============================================

interface User {
  id: string;
  username: string;
  email: string;
  password: string;
  age: number;
  createdAt: Date;
}

// Public profile - exclude sensitive data
type PublicUser = Omit<User, 'password'>;

// User list view - exclude password and detailed timestamps
type UserListItem = Omit<User, 'password' | 'createdAt'>;

// Safe for logging - exclude password
type SafeUser = Omit<User, 'password'>;

function displayPublicProfile(user: PublicUser): void {
  console.log('Public Profile:', {
    id: user.id,
    username: user.username,
    email: user.email,
    age: user.age
  });
  // Can't access user.password - TypeScript error
}

function logUserAction(user: SafeUser, action: string): void {
  console.log(`[LOG] ${user.username} performed: ${action}`);
  // Safe to log - no password in type
}

const fullUser: User = {
  id: '1',
  username: 'john_doe',
  email: 'john@example.com',
  password: 'hashed_password_123',
  age: 30,
  createdAt: new Date()
};

// Create safe version for public display
const publicUser: PublicUser = {
  id: fullUser.id,
  username: fullUser.username,
  email: fullUser.email,
  age: fullUser.age,
  createdAt: fullUser.createdAt
};

displayPublicProfile(publicUser);

console.log('✅ Example 1: Basic Omit completed\n');


