// Example 3: Create vs Update Input Types
// ============================================

interface BlogPost {
  id: string;              // Generated by database
  title: string;
  slug: string;            // Generated from title
  content: string;
  authorId: string;
  published: boolean;
  viewCount: number;       // Managed by system
  createdAt: Date;         // Generated by system
  updatedAt: Date;         // Generated by system
  publishedAt?: Date;      // Generated when published
}

// Create input - user doesn't provide system-generated fields
type CreateBlogPostInput = Omit<
  BlogPost,
  'id' | 'slug' | 'viewCount' | 'createdAt' | 'updatedAt' | 'publishedAt'
>;

// Update input - user can't change id, author, or timestamps
type UpdateBlogPostInput = Omit<
  BlogPost,
  'id' | 'authorId' | 'slug' | 'viewCount' | 'createdAt' | 'updatedAt' | 'publishedAt'
>;

class BlogPostService {
  private posts: Map<string, BlogPost> = new Map();
  private idCounter = 1;

  create(input: CreateBlogPostInput): BlogPost {
    const post: BlogPost = {
      ...input,
      id: `post-${this.idCounter++}`,
      slug: this.generateSlug(input.title),
      viewCount: 0,
      createdAt: new Date(),
      updatedAt: new Date(),
      publishedAt: input.published ? new Date() : undefined
    };

    this.posts.set(post.id, post);
    console.log(`Post created: ${post.title}`);
    return post;
  }

  update(id: string, input: UpdateBlogPostInput): BlogPost | undefined {
    const existing = this.posts.get(id);

    if (!existing) {
      console.log(`Post ${id} not found`);
      return undefined;
    }

    const updated: BlogPost = {
      ...existing,
      ...input,
      updatedAt: new Date(),
      publishedAt: input.published && !existing.published ? new Date() : existing.publishedAt
    };

    this.posts.set(id, updated);
    console.log(`Post updated: ${id}`);
    return updated;
  }

  private generateSlug(title: string): string {
    return title.toLowerCase().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, '');
  }
}

const blogService = new BlogPostService();

// Create post - only provide user-controlled fields
const newPost = blogService.create({
  title: 'Getting Started with TypeScript',
  content: 'TypeScript is a typed superset of JavaScript...',
  authorId: 'user-123',
  published: false
});

console.log('New post:', newPost);

// Update post - can't change id, author, or timestamps
if (newPost) {
  blogService.update(newPost.id, {
    title: 'Getting Started with TypeScript - Updated',
    content: 'Updated content...',
    published: true
  });
}

console.log('✅ Example 3: Create vs Update Types completed\n');


