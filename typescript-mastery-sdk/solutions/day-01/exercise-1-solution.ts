// Exercise 1 Solution: Variables with Types

// 1. Variable for name (string type)
const name: string = "Talha";

// 2. Variable for age (number type)
const age: number = 25;

// 3. Variable isLearningTypeScript (boolean)
const isLearningTypeScript: boolean = true;

// 4. Variable for city (string type)
const city: string = "Karachi";

// 5. Print all variables
console.log("Name:", name);
console.log("Age:", age);
console.log("Learning TypeScript:", isLearningTypeScript);
console.log("City:", city);

// Expected Output:
// Name: Talha
// Age: 25
// Learning TypeScript: true
// City: Karachi

// ✅ Key Learnings:
// - Type annotations syntax: variableName: type
// - const for values that won't change
// - TypeScript enforces the declared types
